/*
 * Русская микротипографика для текстов лендинга.
 * Правило: висячие предлоги/союзы и короткие слова (1–2 буквы) не остаются в конце
 * строки — склеиваются со следующим словом неразрывным пробелом ( ). Также число
 * не отрывается от единицы измерения («30 минут», «10 км», «15%»).
 * Применять ко ВСЕМ текстовым props секций (заголовки, подзаголовки, буллеты, отзывы).
 */

const NBSP = ' ';

// короткие слова (1–2 буквы) + частые 3-буквенные предлоги/союзы/частицы
const SHORT = '[А-ЯЁа-яёA-Za-z]{1,2}|для|или|что|как|под|над|при|без|это|уже|где|чем|кто|так|его|ещё|нам|вам';
const SHORT_RE = new RegExp(`(^|[\\s(«„"])(${SHORT})[ \\t]+`, 'giu');

export function nbsp(input?: string): string {
  if (!input) return input ?? '';
  let s = input;
  let prev = '';
  // повторяем, пока сходится: соседние короткие слова («и в Москве») склеиваются по цепочке
  while (s !== prev) {
    prev = s;
    s = s.replace(SHORT_RE, `$1$2${NBSP}`);
  }
  // разряды числа не разрываются: «40 000», «18 000+» — пробел-разделитель внутри числа
  s = s.replace(/(\d)[ \t]+(?=\d)/gu, `$1${NBSP}`);
  // число + следующее слово / процент / знак валюты — единое целое («1 100 ₽», «30 минут»)
  s = s.replace(/(\d)[ \t]+(?=[А-ЯЁа-яёA-Za-z%₽$€£¥])/gu, `$1${NBSP}`);
  // тире не начинает строку — неразрывный пробел перед ним
  s = s.replace(/[ \t]+([—–])[ \t]/gu, `${NBSP}$1 `);
  return s;
}
