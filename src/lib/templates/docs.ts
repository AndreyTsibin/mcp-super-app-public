/** README files (+ seed docs) to materialize for a profile. */
export function docsPlan(profile: Profile, name = "проект"): DocFile[] {
  const readmes = PROFILE_DIRS[profile].map((dir) => ({
    relPath: `docs/${dir}/README.md`,
    content: README[dir] ?? `# ${dir.split("/").pop()}\n`,
  }));
  return [...readmes, ...seedFiles(name)];
}
